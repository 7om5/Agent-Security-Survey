const rows = scores.map(r => {
  const f = F[r.code];
  if (r.level === 'primary') {
    return {
      ...r,
      F_master: null,
      F_crypto_leverage: null,
      F_low_ai_compute: null,
      F_open_experiment: null,
      F_definability: null,
      F_rationale: '未评价：F 只在二级方向评分，一级方向不聚合，避免用 0 冒充“已评价”。',
      F_limitations: '',
      F_evidence_source: ''
    };
  }
  if (!f) throw new Error(`missing F for ${r.code}`);
  const [fm, lev, lowAI, open, def, rationale, limitations, evidence] = f;
  if (lev + lowAI + open + def !== fm) throw new Error(`F subscores do not sum for ${r.code}: ${lev}+${lowAI}+${open}+${def} != ${fm}`);
  return {
    ...r,
    F_master: fm,
    F_crypto_leverage: lev,
    F_low_ai_compute: lowAI,
    F_open_experiment: open,
    F_definability: def,
    F_rationale: rationale,
    F_limitations: limitations,
    F_evidence_source: evidence
  };
});

